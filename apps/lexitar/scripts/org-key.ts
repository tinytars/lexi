// W44 cutover — the org OPERATIONAL key. A single ECDH keypair whose private key is wrapped under
// an org passphrase. The public key wraps every vault's DEK into an org-recovery envelope at
// migration/signup; the private key lets the CLI/ops pipeline (vault-build/reconcile/vault-verify/
// migrate) unwrap any vault's DEK and keep the plaintext-truth + key-loss-proof model working under
// v2 (see 44-w44 §H / Open decision #1).
//
// IT IS NOT IN THIS REPOSITORY, and the header here used to say the opposite — that the file was
// "committed (records/org-key.json) per this repo's private-secret policy". That policy was
// withdrawn when the repository went public on 2026-09-09, and the sentence outliving it is how the
// private half of a key holding a recovery envelope on every vault came to be published. The file
// now resolves from the operator's credential store, generated by `npm run org:key`, and the
// resolution order below is what makes the in-repo path unreachable rather than merely discouraged:
// there is no fallback to it.
//
//   ORG_KEY_PATH                           explicit override — one file, named outright
//   $LEXI_CREDENTIALS_DIR/org-key.json     the normal case, since 2026-10-08
//   $PLOVER_CREDENTIALS_DIR/org-key.json   the fallback, consulted only on a miss
//
// The key moved stores on 2026-10-08 — it is LexiTar's alone, so it went to tinytars/lexi-keys —
// and these three lines named the old store until this commit. credentialPath() searches both in
// that order, so this estate resolves either way and a cloner sets only the first.
//
// The override exists for the rotation: replacing this key means opening every vault with the OLD
// one and re-wrapping to the NEW one, so both have to be loadable in a single run. That is the only
// supported reason to point this anywhere else.
//
// The passphrase is read from ORG_KEY_PASSPHRASE (never hardcoded, never in this repo).

import { readFileSync, existsSync } from "node:fs";
import { deriveKekFromPassword, unwrapPrivateKey } from "@tinytars/vault/crypto";
import { credentialPath, missingCredential } from "./creds-dir";

export const ORG_KEY_PATH = process.env.ORG_KEY_PATH ?? credentialPath("org-key.json");

export interface OrgKeyFile {
  publicKeyJwk: JsonWebKey;
  wrappedPrivateKey: string; // base64 of iv(12)+AES-GCM(PKCS8)
  kdfParams: { salt: string; iterations: number };
  createdAt: string;
}

export const b64ToBytes = (b64: string): Uint8Array => Uint8Array.from(Buffer.from(b64, "base64"));
export const bytesToB64 = (u: Uint8Array): string => Buffer.from(u).toString("base64");
export const hexToBytes = (h: string): Uint8Array => Uint8Array.from(Buffer.from(h, "hex"));
export const bytesToHex = (u: Uint8Array): string => Buffer.from(u).toString("hex");

export function orgKeyExists(): boolean {
  return existsSync(ORG_KEY_PATH);
}

export function loadOrgKeyFile(): OrgKeyFile {
  // Named in the error rather than left to ENOENT: the two ways this fails — no credential store on
  // this machine, or an ORG_KEY_PATH pointing somewhere stale — look identical from a stack trace,
  // and the fix differs. That distinction was promised here and not made until 2026-10-08: one
  // message named PLOVER_CREDENTIALS_DIR whatever had gone wrong, which after the store split was
  // the wrong variable for the ordinary case. missingCredential() lists every directory actually
  // searched and both variables; the override branch names the one path the operator chose.
  // See apps/lexitar/CREDENTIALS.md.
  if (!existsSync(ORG_KEY_PATH)) {
    throw new Error(
      process.env.ORG_KEY_PATH
        ? `org key not found at ${ORG_KEY_PATH}, which ORG_KEY_PATH names. Unset it to search the ` +
          "credential stores instead; `npm run org:key` mints a new key."
        : `${missingCredential("org-key.json")}\nIt is not committed in this repository; ` +
          "`npm run org:key` mints a new one.",
    );
  }
  return JSON.parse(readFileSync(ORG_KEY_PATH, "utf8")) as OrgKeyFile;
}

export function loadOrgPublicKey(): JsonWebKey {
  return loadOrgKeyFile().publicKeyJwk;
}

export function orgPassphrase(): string {
  const p = process.env.ORG_KEY_PASSPHRASE;
  if (!p) throw new Error("ORG_KEY_PASSPHRASE is not set");
  return p;
}

export async function loadOrgPrivateKey(passphrase = orgPassphrase()): Promise<CryptoKey> {
  const f = loadOrgKeyFile();
  const kek = await deriveKekFromPassword(passphrase, hexToBytes(f.kdfParams.salt));
  return unwrapPrivateKey(b64ToBytes(f.wrappedPrivateKey), kek);
}
